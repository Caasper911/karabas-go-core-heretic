#!/usr/bin/env python3
# Ф1: font8.h (ASCII 32..126, 8x8, one byte per row, bit 7 = left) from a PSF console font of the
# host (console-setup Lat15-VGA8: the IBM VGA 8x8 glyphs), for the on-screen log (kg_hw.c).
import gzip, sys
src = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/consolefonts/Lat15-VGA8.psf.gz'
d = gzip.open(src).read()
if d[:2] == b'\x36\x04':          # PSF1
    h = d[3]; off = 4
else:                              # PSF2
    import struct
    off, h = struct.unpack('<8x I 8x I', d[:24])[0], struct.unpack('<I', d[24:28])[0]
    off = struct.unpack('<I', d[8:12])[0]
assert h == 8, h
# PSF1 with a unicode table: glyph i is code i for ASCII in these fonts
out = ['/* generated by mkfont.py from %s: ASCII 32..126, 8x8 */' % src.split('/')[-1],
       'static const unsigned char font8[95][8] = {']
for c in range(32, 127):
    g = d[off + c * h: off + c * h + 8]
    out.append('    {' + ','.join('0x%02x' % b for b in g) + '},')
out.append('};')
open('font8.h', 'w').write('\n'.join(out) + '\n')
